/**
 * Release check (Phase 6 §4.11), Build 4 (4.0.0). Owner: W4-G. Runs every check of `docs/release/build-3-checklist.md`
 * that a script can do and lists the rest as manual or owner steps. Build 4 adds its acceptance audit and the two
 * vendored Fredoka font files (Phase 7 §4.9), the only font files allowed.
 *
 *   node scripts/check-release.ts               # build into dist/, run the save and locale tests, check everything
 *   node scripts/check-release.ts --no-build    # use the dist/ that is there
 *   node scripts/check-release.ts --no-tests    # skip the Vitest runs
 *
 * Exit code 1 when an automated check fails. Node 22.18+ runs this TypeScript file directly; no dependencies.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { gzipSync } from 'node:zlib';

export type Status = 'pass' | 'fail' | 'manual' | 'owner';

export interface CheckResult {
  /** §4.11 item number. */
  item: number;
  name: string;
  status: Status;
  detail: string;
}

/** Master §10: initial load budget, gzipped JS + CSS. */
export const INITIAL_LOAD_BUDGET_BYTES = 400 * 1024;
export const RELEASE_VERSION = '4.0.0';

/** Names of other games, studios, and parks that must not appear (master §1.3; checklist item 7). */
const THIRD_PARTY = /roller ?coaster tycoon|openrct|\brct ?[123]\b|planet coaster|parkitect|theme park world|sim theme park|thrillville|chris sawyer|hasbro|\batari\b|frontier developments|bullfrog|disneyland|six flags|cedar fair|universal studios/i;
/** Media that is not drawn or generated by the project (audio of any kind, fonts, raster art outside the allowed places). */
const AUDIO = /\.(mp3|ogg|oga|wav|m4a|aac|flac|opus|mid|midi)$/i;
const FONT = /\.(woff2?|ttf|otf|eot)$/i;
const RASTER = /\.(png|jpe?g|gif|webp|avif|bmp|ico)$/i;
/** Raster files the project makes itself: app icons (`scripts/make-icons.ts`) and screenshots of the game. */
const RASTER_ALLOWED = /^(public\/icons\/icon-\d+\.png|docs\/screenshots\/[\w-]+\.png)$/;
/**
 * The only font files allowed (Phase 7 §4.9): the two Fredoka WOFF2 files vendored with their SIL OFL 1.1 licence in
 * `src/assets/fonts/fredoka/`, at their exact sizes, in the repository and as hashed assets in the build.
 */
export const FONTS_ALLOWED: ReadonlyArray<{ name: string; bytes: number }> = [
  { name: 'fredoka-latin-wght-normal', bytes: 29_732 },
  { name: 'fredoka-latin-ext-wght-normal', bytes: 4_576 },
];

/** True for one of the two vendored Fredoka files at its exact size, at its repository path or as a built asset. */
export function allowedFont(path: string, bytes: number | undefined): boolean {
  return FONTS_ALLOWED.some((f) => bytes === f.bytes && (path === `src/assets/fonts/fredoka/${f.name}.woff2` || new RegExp(`^assets/${f.name}-[A-Za-z0-9_-]{6,}\\.woff2$`).test(path)));
}

/** Problems in the tracked files: third-party names in text, and media the project did not make. */
export function originalityProblems(files: ReadonlyArray<{ path: string; text: string | null; bytes?: number }>): string[] {
  const out: string[] = [];
  for (const f of files) {
    if (AUDIO.test(f.path)) out.push(`${f.path}: audio file (all audio is generated in code)`);
    else if (FONT.test(f.path) && !allowedFont(f.path, f.bytes)) out.push(`${f.path}: font file`);
    else if (RASTER.test(f.path) && !RASTER_ALLOWED.test(f.path)) out.push(`${f.path}: image not made by the project`);
    if (f.text !== null && f.path !== 'scripts/check-release.ts') {
      const m = THIRD_PARTY.exec(f.text);
      if (m) out.push(`${f.path}: names "${m[0]}"`);
    }
  }
  return out;
}

function listFiles(root: string, dir = root): string[] {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? listFiles(root, p) : [relative(root, p).split(sep).join('/')];
  });
}

/** Problems with the offline files of a build in `dist` (Phase 6 §4.10). */
export function distProblems(dist: string): string[] {
  if (!existsSync(join(dist, 'index.html'))) return [`${dist}/index.html is missing (build first)`];
  const out: string[] = [];
  const files = listFiles(dist);
  const hashed = files.filter((f) => f.startsWith('assets/') && !f.endsWith('.map')).sort();
  let manifest: { buildId?: unknown; assets?: unknown } = {};
  try {
    manifest = JSON.parse(readFileSync(join(dist, 'sw-manifest.json'), 'utf8')) as typeof manifest;
  } catch {
    out.push('sw-manifest.json is missing or not JSON');
  }
  const listed = Array.isArray(manifest.assets) ? [...(manifest.assets as string[])].sort() : [];
  if (JSON.stringify(listed) !== JSON.stringify(hashed)) out.push(`sw-manifest.json lists ${listed.length} assets, the build has ${hashed.length}`);
  const sw = existsSync(join(dist, 'sw.js')) ? readFileSync(join(dist, 'sw.js'), 'utf8') : '';
  if (sw === '') out.push('sw.js is missing');
  else if (sw.includes('__TC_BUILD_ID__') || typeof manifest.buildId !== 'string' || !sw.includes(`'${manifest.buildId}'`)) out.push('sw.js does not carry the build id of sw-manifest.json');
  for (const f of files) if (AUDIO.test(f)) out.push(`${f}: audio file in the build`);
  for (const f of files) if (FONT.test(f) && !allowedFont(f, statSync(join(dist, f)).size)) out.push(`${f}: font file in the build`);
  for (const f of ['manifest.webmanifest', 'icons/icon.svg', 'icons/icon-180.png', 'icons/icon-192.png', 'icons/icon-512.png']) if (!files.includes(f)) out.push(`${f} is missing`);
  return out;
}

/** Gzipped size of the JS and CSS the page loads first (the files `index.html` names). */
export function initialLoadBytes(dist: string): number {
  const html = readFileSync(join(dist, 'index.html'), 'utf8');
  let total = 0;
  for (const m of html.matchAll(/(?:src|href)="\.?\/?([^"]+\.(?:js|css))"/g)) total += gzipSync(readFileSync(join(dist, m[1] as string))).length;
  return total;
}

/** One row of an acceptance audit's "| # | Done when" table: its number, its line, and its result (PASS, OPEN, ...). */
export interface AuditRow {
  id: string;
  line: string;
  result: string;
}

/** The rows of every "| # | Done when" table of an acceptance audit (the header and the separator row are skipped). */
export function auditRows(text: string): AuditRow[] {
  const out: AuditRow[] = [];
  let inTable = false;
  for (const raw of text.split('\n')) {
    const l = raw.trim();
    if (/^\|\s*#\s*\|\s*Done when/.test(l)) {
      inTable = true;
      continue;
    }
    if (!inTable) continue;
    if (!l.startsWith('|')) {
      inTable = false;
      continue;
    }
    if (/^\|[\s|:-]+\|$/.test(l)) continue;
    const cells = l.slice(1).split(/(?<!\\)\|/).map((c) => c.trim());
    out.push({ id: cells[0] ?? '', line: cells[1] ?? '', result: cells[2] ?? '' });
  }
  return out;
}

/** Owner items of the audits: each "Done when" row whose result is OPEN or GAP (a person must close it). */
export function auditOwnerItems(audits: Readonly<Record<string, string | null>>): Array<{ name: string; path: string }> {
  const out: Array<{ name: string; path: string }> = [];
  for (const [path, text] of Object.entries(audits)) {
    if (text === null) continue;
    const file = path.split('/').pop() ?? path;
    for (const r of auditRows(text)) if (/^(OPEN|GAP)\b/.test(r.result)) out.push({ name: `Owner: ${r.line} (${file} ${r.id}, ${r.result})`, path });
  }
  return out;
}

/**
 * Item 1: rows of the checklist's "Phase 6 done when" table still marked PENDING, acceptance audits that are missing
 * or have no result line (`docs/superpowers/specs/thrills-and-chills/build-{2,3,4}-acceptance.md`), and audit "Done
 * when" rows whose result is FAIL or PENDING.
 */
export function doneWhenProblems(checklist: string, audits: Readonly<Record<string, string | null>>): string[] {
  const out: string[] = [];
  const start = checklist.indexOf('## Phase 6 done when');
  if (start < 0) out.push('the checklist has no "Phase 6 done when" table');
  else {
    const rest = checklist.slice(start + 1);
    const end = rest.indexOf('\n## ');
    const rows = (end < 0 ? rest : rest.slice(0, end)).split('\n').filter((l) => l.startsWith('| ') && !/^\|\s*Done-when item/.test(l));
    if (rows.length === 0) out.push('the "Phase 6 done when" table is empty');
    for (const row of rows) {
      const cells = row.split(' | ');
      const status = (cells[cells.length - 1] ?? '').replace(/\|\s*$/, '');
      if (/PENDING/.test(status)) out.push(`still PENDING: ${(cells[0] ?? '').replace(/^\|\s*/, '').slice(0, 60)}`);
    }
  }
  for (const [path, text] of Object.entries(audits)) {
    if (text === null) out.push(`${path} is missing`);
    else if (!/^\*\*Result:/m.test(text)) out.push(`${path} has no result line`);
    if (text !== null) for (const r of auditRows(text)) if (/^(FAIL|PENDING)\b/.test(r.result)) out.push(`${path} ${r.id} is ${r.result}: ${r.line.slice(0, 60)}`);
  }
  return out;
}

const kb = (n: number): string => `${(n / 1024).toFixed(1)} KB`;

function run(cmd: string, args: string[], cwd: string): { ok: boolean; out: string } {
  try {
    const out = execFileSync(cmd, args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
    return { ok: true, out };
  } catch (e) {
    const err = e as { stdout?: string; stderr?: string; message: string };
    return { ok: false, out: `${err.stdout ?? ''}${err.stderr ?? ''}` || err.message };
  }
}

function lastLine(text: string, pattern: RegExp): string {
  return (
    text
      .split('\n')
      .map((l) => l.replace(/\x1b\[[0-9;]*m/g, '').trim())
      .filter((l) => pattern.test(l))
      .pop() ?? ''
  );
}

export function checkRelease(root: string, opts: { build: boolean; tests: boolean }): CheckResult[] {
  const results: CheckResult[] = [];
  const add = (item: number, name: string, status: Status, detail: string): void => {
    results.push({ item, name, status, detail });
  };

  // 1. Done-when items and CI.
  const read = (p: string): string | null => (existsSync(join(root, p)) ? readFileSync(join(root, p), 'utf8') : null);
  const auditPaths = ['build-2', 'build-3', 'build-4'].map((b) => `docs/superpowers/specs/thrills-and-chills/${b}-acceptance.md`);
  const dw = doneWhenProblems(read('docs/release/build-3-checklist.md') ?? '', Object.fromEntries(auditPaths.map((p) => [p, read(p)])));
  add(1, 'Done-when rows decided (none PENDING, no audit line FAIL); Build 2, 3, and 4 acceptance audits written', dw.length === 0 ? 'pass' : 'fail', dw.length === 0 ? 'docs/release/build-3-checklist.md, build-2-acceptance.md, build-3-acceptance.md, build-4-acceptance.md' : dw.join('; '));
  // Audit lines that a person must close (OPEN or GAP) are owner items; they never fail the check.
  for (const o of auditOwnerItems(Object.fromEntries(auditPaths.map((p) => [p, read(p)])))) add(1, o.name, 'owner', o.path);
  add(1, 'CI green on the release commit', 'manual', 'GitHub Actions (typecheck, unit, build, e2e desktop and phone) on the commit that is tagged');

  // 2. Performance.
  const dist = join(root, 'dist');
  if (opts.build) {
    const b = run('npx', ['vite', 'build', '--logLevel', 'error'], root);
    if (!b.ok) add(2, 'Build', 'fail', b.out.slice(-400));
  }
  if (existsSync(join(dist, 'index.html'))) {
    const bytes = initialLoadBytes(dist);
    add(2, 'Initial load < 400 KB gzip (master §10)', bytes < INITIAL_LOAD_BUDGET_BYTES ? 'pass' : 'fail', `${kb(bytes)} gzipped JS + CSS (${bytes} bytes)`);
  } else add(2, 'Initial load < 400 KB gzip (master §10)', 'fail', 'no dist/ build');
  add(2, 'Perf runs meet §4.6 budgets or the gap is in the release notes', 'manual', 'tests/e2e/perf-build3.spec.ts and docs/adr/ (W4-E)');

  // 3. Accessibility.
  const a11ySpec = existsSync(join(root, 'tests/e2e/a11y.spec.ts'));
  add(3, 'Accessibility scan: no serious or critical issues', a11ySpec ? 'manual' : 'fail', a11ySpec ? 'tests/e2e/a11y.spec.ts runs in CI (W4-F); confirm it is green' : 'tests/e2e/a11y.spec.ts is missing');

  // 4. Browsers.
  add(4, 'Manual checks: Chrome, Firefox, Safari (desktop); Android Chrome, iOS Safari', 'manual', 'Steps in docs/release/build-3-checklist.md');

  // 5. Saves and progress.
  const fixtures = ['tests/fixtures/save-v1.tcsave.json', 'tests/fixtures/save-v2.tcsave.json', 'tests/fixtures/progress-v2.json'];
  const missingFixtures = fixtures.filter((f) => !existsSync(join(root, f)));
  if (missingFixtures.length > 0) add(5, 'Fixture saves 1 → 2 → 3 and a Build 2 progress file load', 'fail', `missing ${missingFixtures.join(', ')}`);
  else if (opts.tests) {
    const t = run('npx', ['vitest', 'run', 'tests/unit/save/migrate-v1.test.ts', 'tests/unit/save/migrate-v2.test.ts', 'tests/unit/save/progress-v2.test.ts'], root);
    add(5, 'Fixture saves 1 → 2 → 3 and a Build 2 progress file load', t.ok ? 'pass' : 'fail', lastLine(t.out, /Tests\s/) || 'vitest failed');
  } else add(5, 'Fixture saves 1 → 2 → 3 and a Build 2 progress file load', 'manual', 'run with tests: npx vitest run tests/unit/save');

  // 6. Offline play.
  const dp = existsSync(join(dist, 'index.html')) ? distProblems(dist) : ['no dist/ build'];
  add(6, 'Build ships sw.js, sw-manifest.json (every hashed asset), web manifest, icons', dp.length === 0 ? 'pass' : 'fail', dp.length === 0 ? 'dist/ checked' : dp.join('; '));
  add(6, 'Service worker update flow works on the Pages URL', 'manual', 'Steps in docs/release/build-3-checklist.md (two deploys)');

  // Localization (Phase 6 §10 "adding a language follows 4.8"; CI blocks a locale with a missing key).
  if (opts.tests) {
    const t = run('npx', ['vitest', 'run', 'tests/unit/i18n'], root);
    add(1, 'Every locale complete, placeholders match (en, en-XA)', t.ok ? 'pass' : 'fail', lastLine(t.out, /Tests\s/) || 'vitest failed');
  }

  // 7. Originality.
  const ls = run('git', ['ls-files'], root);
  if (!ls.ok) add(7, 'Originality: no third-party names, art, audio, or data', 'fail', 'git ls-files failed');
  else {
    const files = ls.out
      .split('\n')
      .filter((p) => p !== '' && p !== 'package-lock.json' && existsSync(join(root, p)))
      .map((path) => ({ path, text: /\.(ts|js|json|md|html|css|svg|webmanifest|yml|yaml|txt)$/.test(path) ? readFileSync(join(root, path), 'utf8') : null, bytes: statSync(join(root, path)).size }));
    const op = originalityProblems(files);
    add(7, 'Originality: no third-party names, art, audio, or data', op.length === 0 ? 'pass' : 'fail', op.length === 0 ? `${files.length} tracked files scanned; also review by hand` : op.join('; '));
  }

  // 8. Version, changelog, readme, license.
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { version?: string };
  add(8, `gameVersion is ${RELEASE_VERSION} (package.json)`, pkg.version === RELEASE_VERSION ? 'pass' : 'fail', `package.json version ${pkg.version ?? '(none)'}`);
  const changelog = existsSync(join(root, 'CHANGELOG.md')) ? readFileSync(join(root, 'CHANGELOG.md'), 'utf8') : '';
  add(8, 'CHANGELOG has a Build 4 section', /^##\s.*Build 4/m.test(changelog) ? 'pass' : 'fail', changelog === '' ? 'CHANGELOG.md is missing' : 'CHANGELOG.md');
  const readme = existsSync(join(root, 'README.md')) ? readFileSync(join(root, 'README.md'), 'utf8') : '';
  const readmeOk = /Build 4/.test(readme) && /no affiliation/i.test(readme);
  add(8, 'README covers Build 4 and the originality statement', readmeOk ? 'pass' : 'fail', 'README.md');
  const license = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'COPYING'].find((f) => existsSync(join(root, f)));
  add(8, "The owner's license file exists", license ? 'pass' : 'owner', license ?? 'The owner has not chosen a license yet (master §12); no license file is added until then');

  // 9. Tag and release notes.
  const tag = run('git', ['tag', '--list', 'build-4'], root);
  add(9, 'Tag build-4 and publish release notes', tag.ok && tag.out.trim() === 'build-4' ? 'pass' : 'manual', "After the owner's go: git tag build-4; release notes from CHANGELOG.md");

  return results.sort((a, b) => a.item - b.item);
}

export function formatResults(results: readonly CheckResult[]): string {
  const icon: Record<Status, string> = { pass: 'PASS', fail: 'FAIL', manual: 'MANUAL', owner: 'OWNER' };
  const rows = results.map((r) => `| ${r.item} | ${r.name} | ${icon[r.status]} | ${r.detail.replace(/\|/g, '\\|')} |`);
  return ['| # | Check | Status | Detail |', '|---|---|---|---|', ...rows].join('\n');
}

function main(): void {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const args = new Set(process.argv.slice(2));
  const results = checkRelease(root, { build: !args.has('--no-build'), tests: !args.has('--no-tests') });
  console.log(formatResults(results));
  const failed = results.filter((r) => r.status === 'fail').length;
  console.log(`\n${failed === 0 ? 'No automated check failed' : `${failed} automated check(s) failed`}; MANUAL and OWNER rows need a person`);
  process.exitCode = failed === 0 ? 0 : 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
